#!/bin/bash
# Скрипт для запуска проекта Калькулятор
# Автор: Владимир Макрушин

echo "=========================================="
echo "   Запуск проекта Калькулятор"
echo "=========================================="

# Переход в папку скрипта (важно для запуска из любой директории)
cd "$(dirname "$0")"

# Активация виртуального окружения
echo "[1/3] Активация виртуального окружения..."
if [ ! -d "venv" ]; then
    echo "ОШИБКА: Виртуальное окружение не найдено!"
    echo "Создайте его командой: python3 -m venv venv"
    exit 1
fi
source venv/bin/activate

# Проверка наличия зависимостей
echo "[2/3] Проверка зависимостей..."
if ! python -c "import pytest" 2>/dev/null; then
    echo "Установка зависимостей из requirements.txt..."
    pip install -r requirements.txt
fi

# Запуск программы
echo "[3/3] Запуск калькулятора..."
echo "=========================================="
python main.py

# Деактивация окружения после завершения
deactivate
echo "=========================================="
echo "   Программа завершена"
echo "=========================================="

