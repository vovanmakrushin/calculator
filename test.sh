#!/bin/bash
# Скрипт для запуска тестов проекта
# Автор: Владимир Макрушин

echo "=========================================="
echo "   Запуск тестов проекта"
echo "=========================================="

cd "$(dirname "$0")"

# Активация окружения
if [ ! -d "venv" ]; then
    echo "ОШИБКА: Виртуальное окружение не найдено!"
    exit 1
fi
source venv/bin/activate

# Запуск тестов с подробным выводом
echo "Запуск pytest..."
echo "------------------------------------------"
pytest -v

# Сохраняем код возврата pytest
EXIT_CODE=$?

deactivate

echo "------------------------------------------"
if [ $EXIT_CODE -eq 0 ]; then
    echo "✅ Все тесты пройдены успешно!"
else
    echo "❌ Некоторые тесты провалились. Код ошибки: $EXIT_CODE"
fi
echo "=========================================="

exit $EXIT_CODE

